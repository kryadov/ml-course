"""День 2 — broadcasting, индексация и нормализация данных."""
import numpy as np

m = np.arange(1, 13).reshape(3, 4)
print("матрица m:\n", m)

# --- 1. Broadcasting ------------------------------------------------------
# вычесть среднее КАЖДОГО СТОЛБЦА из всех его значений
col_mean = m.mean(axis=0)                  # форма (4,)
print("\nсредние по столбцам:", col_mean)
print("центрированное (m - col_mean):\n", m - col_mean)   # (3,4) - (4,)

# прибавить вектор к КАЖДОМУ СТОЛБЦУ — нужна форма (3, 1)
row_bias = np.array([[10], [20], [30]])    # форма (3, 1)
print("\nсдвиг по строкам (m + row_bias):\n", m + row_bias)

# --- 2. Индексация и срезы ------------------------------------------------
print("\nm[1, 2] =", m[1, 2])             # элемент: строка 1, столбец 2
print("m[:, 0]  =", m[:, 0])              # весь столбец 0
print("m[0:2, 1:3]:\n", m[0:2, 1:3])      # подматрица
print("m[[0, 2], :] (fancy):\n", m[[0, 2], :])  # строки 0 и 2

# --- 3. Мини-задание: стандартизация (z-score) ----------------------------
# Реальный шаг предобработки: каждый признак (столбец) приводим к
# среднему 0 и стандартному отклонению 1. Формула: (x - mean) / std.
# Строки = объекты (samples), столбцы = признаки (features).
X = np.array([
    [50.0, 1.0, 200.0],
    [60.0, 0.0, 150.0],
    [55.0, 1.0, 300.0],
    [65.0, 0.0, 250.0],
])
mean = X.mean(axis=0)          # среднее по каждому признаку, форма (3,)
std = X.std(axis=0)            # стандартное отклонение,       форма (3,)
X_scaled = (X - mean) / std    # broadcasting: (4,3) - (3,) / (3,)

print("\n--- стандартизация ---")
print("mean по признакам:", mean)
print("std  по признакам:", std)
print("X_scaled:\n", X_scaled)
# проверка: после стандартизации mean ≈ 0, std ≈ 1 по каждому столбцу
print("проверка mean:", X_scaled.mean(axis=0).round(6))
print("проверка std: ", X_scaled.std(axis=0).round(6))
