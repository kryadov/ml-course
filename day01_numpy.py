"""День 1 — первый контакт с NumPy. Ключевая идея: векторизация."""
import numpy as np

a = np.arange(1, 13)  # вектор 1..12
print(a)
print(a.shape, a.dtype)

m = a.reshape(3, 4)  # матрица 3x4
print(m)
print("сумма по столбцам:", m.sum(axis=0))
print("среднее по строкам:", m.mean(axis=1))

# векторизация вместо цикла — фундамент NumPy, pandas и PyTorch
print("квадраты:", a**2)
print("только чётные:", a[a % 2 == 0])

# --- Мини-задание: ---
print("\n--- мини-задание ---")
r = np.random.rand(20)                      # 20 случайных чисел в [0, 1)
print("среднее:", r.mean(), "| станд. отклонение:", r.std())
print("больше среднего:", r[r > r.mean()])  # булева маска = векторизованный фильтр
